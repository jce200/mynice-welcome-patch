"""The position model alone:  python3 tests/test_travel.py"""
import importlib.util, os, sys
spec = importlib.util.spec_from_file_location("travel", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "custom_components", "nicegate", "travel.py"))
travel = importlib.util.module_from_spec(spec); sys.modules["travel"] = travel; spec.loader.exec_module(travel)
T = travel.TravelModel
results = []
def ok(name, cond, extra=""):
    results.append(bool(cond)); print(("ok    " if cond else "FAIL  ") + name + (("   [" + str(extra) + "]") if extra != "" and not cond else ""))

m = T(); m.update("closed", 0, precise=True)
ok("closed is 0, open is 100", m.position_at(1) == 0.0)
m.update("opening", 10, precise=True)
ok("nothing learned yet: the position during the first run is unknown, not a guess", m.position_at(15) is None)
m.update("open", 30, precise=True)
ok("a full run that was heard at both ends teaches the travel time (20 s)", m.travel_time("opening") == 20 and m.position_at(31) == 100.0)
ok("...only for that direction", m.travel_time("closing") is None)
m.update("closing", 40, precise=True); m.update("closed", 64, precise=True)
ok("closing is learned apart (24 s)", m.travel_time("closing") == 24)
m.update("opening", 100, precise=True)
ok("half the time is half the way", m.position_at(110) == 50.0, m.position_at(110))
ok("a run that takes longer than learned waits just before the end", m.position_at(140) == 99.0)
m.update("stopped", 105, precise=True)
ok("stop freezes the gate where it was (25 %), whatever the clock does afterwards", m.position_at(105) == 25.0 and m.position_at(500) == 25.0, m.position_at(105))
ok("...and a run that was stopped teaches nothing", m.runs["opening"] == [20])
m.update("opening", 200, precise=True)
ok("it goes on from there: 25 % + 10 s of 20 s = 75 %", m.position_at(210) == 75.0, m.position_at(210))
m.update("open", 216, precise=True)
ok("...and a run that did not start at an end teaches nothing either", m.runs["opening"] == [20] and m.position_at(216) == 100.0)
m.update("closing", 300, precise=True)
p = m.position_at(306)
m.update("opening", 306, precise=True)
ok("reversed while moving: it turns around where it was (75 %)", p == 75.0 and m.position_at(306) == 75.0 and m.position_at(308) == 85.0, (p, m.position_at(308)))
m.update("open", 311, precise=True)
# a start found by a poll is up to half a minute late: no lesson
m.update("closing", 400, precise=False); m.update("closed", 410, precise=True)
ok("a run whose start was found by a poll is not a measurement", m.runs["closing"] == [24])
m.update("opening", 500, precise=True); m.update("open", 501, precise=True)
ok("a 'run' of one second is a glitch, not a measurement", m.runs["opening"] == [20])
for i, d in enumerate([22, 21, 60, 19, 20, 23]):
    m.update("closed", 1000 + i * 200, precise=True); m.update("opening", 1010 + i * 200, precise=True); m.update("open", 1010 + i * 200 + d, precise=True)
ok("the median of the last five runs: one slow run does not move it", m.runs["opening"] == [21, 60, 19, 20, 23] and m.travel_time("opening") == 21, (m.runs["opening"], m.travel_time("opening")))
ok("a status that the model does not move on (the same again, nothing) changes nothing", (m.update("open", 9000, precise=True), m.update(None, 9001, precise=True), m.status)[2] == "open")
# over a restart
m.update("closing", 9100, precise=True); m.update("stopped", 9106, precise=True)
saved = m.dump(); n = T(); n.load(saved)
ok("saved and loaded: the travel times and a stopped position", n.travel_time("opening") == 21 and n.travel_time("closing") == 24 and n.position_at(0) == 75.0 and n.status == "stopped", (saved, n.position_at(0)))
n.update("closed", 5, precise=False)
ok("...and what the module says after the restart wins", n.position_at(6) == 0.0)
m.update("closing", 9200, precise=True); mid = T(); mid.load(m.dump())
ok("a restart in the middle of a run does not pretend to know where the gate is", mid.status is None and mid.position_at(0) is None)
junk = T(); junk.load({"runs": {"opening": ["x", 1, 500, 20], "closing": None}, "status": "stopped", "position": 400}); junk.load(None); junk.load("x")
ok("junk in the saved data is ignored", junk.runs == {"opening": [20.0], "closing": []} and junk.position is None)
print(("ALL OK (%d checks)" % len(results)) if all(results) else "%d of %d FAILED" % (results.count(False), len(results)))
sys.exit(0 if all(results) else 1)
