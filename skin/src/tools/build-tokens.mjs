// Generates tokens.css: Material 3 color roles (light/dark) from a seed color, plus custom "ok" and "warning" families,
// plus spring curves as CSS linear() (Material 3 Expressive: spatial and effects).
// Run:  npm install && npm run build:tokens   (esbuild bundles it first: the ESM build of the color package has no file extensions,
//        so plain `node build-tokens.mjs` fails with ERR_MODULE_NOT_FOUND). Then run build-css.py in the folder above.
import {
  argbFromHex, hexFromArgb, Hct, MaterialDynamicColors, Blend,
  SchemeVibrant, SchemeTonalSpot, SchemeExpressive, SchemeNeutral, SchemeContent, SchemeFidelity, SchemeRainbow, SchemeFruitSalad, SchemeMonochrome,
} from '@material/material-color-utilities';
// To compare palettes without touching the defaults:  node build-tokens.bundle.mjs --seed '#0B57D0' --scheme tonal [--ok '#2E9D55'] [--warn '#C98200']
const SCHEMES = { vibrant: SchemeVibrant, tonal: SchemeTonalSpot, expressive: SchemeExpressive, neutral: SchemeNeutral, content: SchemeContent,
  fidelity: SchemeFidelity, rainbow: SchemeRainbow, fruit: SchemeFruitSalad, monochrome: SchemeMonochrome };
const args = {};
for (let i = 2; i < process.argv.length; i++) if (process.argv[i].startsWith('--')) args[process.argv[i].slice(2)] = process.argv[++i];
// the palette of the app: a calm petrol blue (Material scheme "tonal spot": soft tonal surfaces, secondary and tertiary in the same family)
const SEED = args.seed || '#1E6A8A';
const SCHEME = args.scheme || 'tonal';
if (!SCHEMES[SCHEME]) throw new Error('unknown scheme ' + SCHEME + ' (' + Object.keys(SCHEMES).join(', ') + ')');
const OK = args.ok || '#2E9D55', WARN = args.warn || '#C98200';
const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const roles = ['primary','onPrimary','primaryContainer','onPrimaryContainer','secondary','onSecondary','secondaryContainer','onSecondaryContainer','tertiary','onTertiary','tertiaryContainer','onTertiaryContainer','error','onError','errorContainer','onErrorContainer','surface','onSurface','surfaceVariant','onSurfaceVariant','outline','outlineVariant','surfaceDim','surfaceBright','surfaceContainerLowest','surfaceContainerLow','surfaceContainer','surfaceContainerHigh','surfaceContainerHighest','inverseSurface','inverseOnSurface','inversePrimary','scrim'];
function baseScheme(dark) {
  const sch = new SCHEMES[SCHEME](Hct.fromInt(argbFromHex(SEED)), dark, 0.0);
  const out = {};
  for (const r of roles) { const dc = MaterialDynamicColors[r]; if (dc) out[r] = hexFromArgb(dc.getArgb(sch)); }
  return { out, sch };
}
// custom families (green = ok, amber = warning), harmonized toward the seed color
function family(hex, dark) {
  const source = Blend.harmonize(argbFromHex(hex), argbFromHex(SEED));
  const s = new SchemeTonalSpot(Hct.fromInt(source), dark, 0.0);
  const f = (n) => hexFromArgb(MaterialDynamicColors[n].getArgb(s));
  return { fam: f('primary'), onFam: f('onPrimary'), famContainer: f('primaryContainer'), onFamContainer: f('onPrimaryContainer') };
}
function colorBlock(dark) {
  const { out, sch } = baseScheme(dark);
  const ok = family(OK, dark), warn = family(WARN, dark);
  const lines = Object.entries(out).map(([k, v]) => `  --md-sys-color-${kebab(k)}: ${v};`);
  for (const [name, f] of [['ok', ok], ['warn', warn]]) {
    lines.push(`  --nx-${name}: ${f.fam};`, `  --nx-on-${name}: ${f.onFam};`, `  --nx-${name}-container: ${f.famContainer};`, `  --nx-on-${name}-container: ${f.onFamContainer};`);
  }
  // the wizard screens: Nice's light-gray icons sit on a dark "stage" or on a "brand" surface; both follow the scheme now
  lines.push(`  --nx-brand: ${hexFromArgb(sch.primaryPalette.tone(dark ? 48 : 36))};`, `  --nx-stage: ${hexFromArgb(sch.neutralVariantPalette.tone(dark ? 14 : 16))};`);
  return lines.join('\n');
}
// spring as CSS linear(): x(t) for a damped spring with damping ratio z and natural frequency w; duration until |x-1| < 0.002
function spring(z, w, points = 40) {
  const x = (t) => { const wd = w * Math.sqrt(1 - z * z); return z < 1 ? 1 - Math.exp(-z * w * t) * (Math.cos(wd * t) + (z * w / wd) * Math.sin(wd * t)) : 1 - Math.exp(-w * t) * (1 + w * t); };
  let T = 0.05; while (T < 3) { let ok = true; for (let t = T; t < T + 0.3; t += 0.01) if (Math.abs(x(t) - 1) > 0.002) { ok = false; break; } if (ok) break; T += 0.01; }
  const parts = []; for (let i = 0; i <= points; i++) { const t = (i / points) * T; parts.push(+x(t).toFixed(4)); }
  parts[parts.length - 1] = 1;
  return { ms: Math.round(T * 1000), linear: 'linear(' + parts.join(', ') + ')' };
}
const spatialFast = spring(0.82, 34), spatialDefault = spring(0.8, 24), spatialSlow = spring(0.85, 15), bouncy = spring(0.55, 26), effects = spring(1.0, 36);
const css = `/* Generated by build-tokens.mjs, seed color ${SEED} (Material scheme "${SCHEME}"). Do not edit by hand. */
:root {
${colorBlock(false)}
  --nx-spring-fast: ${spatialFast.linear};   --nx-spring-fast-ms: ${spatialFast.ms}ms;
  --nx-spring: ${spatialDefault.linear};   --nx-spring-ms: ${spatialDefault.ms}ms;
  --nx-spring-slow: ${spatialSlow.linear};   --nx-spring-slow-ms: ${spatialSlow.ms}ms;
  --nx-spring-bouncy: ${bouncy.linear};   --nx-spring-bouncy-ms: ${bouncy.ms}ms;
  --nx-effects: ${effects.linear};   --nx-effects-ms: ${effects.ms}ms;
}
/* Dark follows the phone (what the WebView reports as prefers-color-scheme) unless the user chose a theme: nx-theme.js and
   nx-patch.js put data-nx-theme="light" or "dark" on <html> (Settings > Theme); "auto" sets nothing. */
@media (prefers-color-scheme: dark) {
  :root:not([data-nx-theme="light"]) {
${colorBlock(true).replace(/^/gm, '  ')}
  }
}
:root[data-nx-theme="dark"] {
${colorBlock(true)}
}
`;
